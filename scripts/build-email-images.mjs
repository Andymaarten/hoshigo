// Turns public/email/*.png into base64 constants for inline (cid:) email images, so they
// travel with the server code and need no file tracing. Run after changing those PNGs:
//   node scripts/build-email-images.mjs
import { readFileSync, writeFileSync } from "node:fs";

const files = { "add-a-hoshigo": "public/email/add-a-hoshigo.png", "app-icon": "public/email/app-icon.png" };
const lines = Object.entries(files).map(
  ([id, path]) => `  "${id}": "${readFileSync(path).toString("base64")}",`
);
writeFileSync(
  "src/lib/email-images.ts",
  `// Generated by scripts/build-email-images.mjs from public/email. Do not edit by hand.
export const EMAIL_IMAGES = {
${lines.join("\n")}
} as const;

export type EmailImageId = keyof typeof EMAIL_IMAGES;
`
);
console.log("ok");
